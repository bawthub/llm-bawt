"""TASK-2130: the product skills baked into the tenant images.

``tenant-skills/`` is generated by agent-skills' ``scripts/export-product-skills``
(see its BUNDLE.json for the source revision). These source guards keep the
vendored copy general-use and wired into both tenant images at one path.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "tenant-skills"
SKILLS_PATH = "/opt/bawthub/skills"

REQUIRED = {"agent-system", "bawthub", "llm-bawt", "git-commits", "frontend-design",
            "ui-ux-guidelines"}
PRIVATE = {"local-infrastructure", "taurus-ops", "unifi-network", "unraid-ops",
           "local-services", "infra-backups", "network-pentest", "bitwarden-cli",
           "bridge-container-network", "tenant-provisioning"}
# Mirrors the exporter's lint: one private installation's names and addresses.
PRIVATE_TEXT = re.compile(
    r"ferreri\.us|zenoran|\b10\.0\.\d{1,3}\.\d{1,3}\b|\b172\.18\.0\.1\b"
    r"|\b192\.168\.\d{1,3}\.\d{1,3}\b|(?i:\btaurus\b)|echo-release|@echo\b|\becho:\d"
    r"|\b(?:on|from|to|in|of|via|at) echo\b|\becho (?:host|DB|disk)\b"
    r"|/home/(?:nick|bawthub)\b"
)


def _meta() -> dict:
    return json.loads((BUNDLE / "BUNDLE.json").read_text())


def test_bundle_lists_exactly_its_skill_directories():
    meta = _meta()
    assert meta["source"] == "agent-skills" and meta["dirty"] is False
    assert re.fullmatch(r"[0-9a-f]{40}", meta["revision"])
    dirs = sorted(p.name for p in BUNDLE.iterdir() if p.is_dir())
    assert dirs == sorted(meta["skills"])
    for name in dirs:
        assert (BUNDLE / name / "SKILL.md").is_file(), name


def test_bundle_ships_product_skills_and_no_private_ones():
    skills = set(_meta()["skills"])
    assert REQUIRED <= skills
    assert not PRIVATE & skills


def test_bundle_has_no_private_references():
    hits = []
    for path in sorted(BUNDLE.rglob("*")):
        if path.is_file():
            for number, line in enumerate(path.read_text().splitlines(), 1):
                if PRIVATE_TEXT.search(line):
                    hits.append(f"{path.relative_to(ROOT)}:{number}")
    assert hits == []


def test_both_tenant_images_bake_the_bundle_at_one_path():
    for dockerfile in ("Dockerfile.app", "Dockerfile.agent-bridge"):
        text = (ROOT / dockerfile).read_text()
        assert f"COPY tenant-skills/ {SKILLS_PATH}/" in text, dockerfile


def test_build_context_keeps_the_bundle():
    # .dockerignore patterns are root-anchored; a recursive one would empty it.
    patterns = [line.strip() for line in (ROOT / ".dockerignore").read_text().splitlines()]
    assert not [p for p in patterns if p.startswith("**") or p.startswith("tenant-skills")]
